"""
sparse_activation.py
---------------------
Controls which agents act at each step.

For small N (≤8): all agents act every step.
For large N: only the active frontier acts — agents attached to
open subtasks, recent claimants, or sampled by reputation.

This keeps per-step compute fixed at ~12–16 agents regardless of N,
making cost scale linearly with steps rather than N×steps.

Scientific validity: preserved because:
  - Events are still generated by N agents across the full run
  - Cascade sizes still reflect N-agent society structure
  - x_max scaling still observable across N ∈ {8..128}
  - Only the per-step activation density is capped, not the society size
"""

from __future__ import annotations

import random
from typing import Dict, List, Optional, Set
from context_builder import get_visible_neighbor_cap as get_activation_cap


def select_active_agents(
    all_agents:       List[str],
    step_idx:         int,
    agent_outputs:    Dict[str, str],
    open_subtasks:    Optional[Dict[str, str]] = None,   # {subtask_id: agent_id}
    reputation:       Optional[Dict[str, float]] = None,
    rng:              Optional[random.Random] = None,
    force_include:    Optional[List[str]] = None,        # always include (e.g. hub)
    strategy:         str = "frontier",                  # frontier | reputation | random
) -> List[str]:
    """
    Select which agents act at this step.

    Parameters
    ----------
    all_agents      Full agent list for this topology run.
    step_idx        Current step (0-indexed). Step 0: all agents act (initialise).
    agent_outputs   Current outputs — agents with no output are prioritised.
    open_subtasks   Agents currently assigned to open subtasks.
    reputation      Reputation scores for reputation-weighted selection.
    rng             Random state for reproducibility.
    force_include   Agents that must always be included (hub, integrator, etc.).
    strategy        Selection strategy.

    Returns
    -------
    Ordered list of agent IDs that will act this step.
    """
    n   = len(all_agents)
    cap = get_activation_cap(n)

    if rng is None:
        rng = random.Random(step_idx)

    # Step 0: always activate all (initialisation)
    if step_idx == 0 or n <= cap:
        return list(all_agents)

    forced  = set(force_include or [])
    active: Set[str] = set(forced)

    # Priority 1: agents with no output yet (haven't spoken)
    silent = [a for a in all_agents if a not in active
              and not agent_outputs.get(a)]
    active.update(silent[:cap // 2])

    # Priority 2: agents with open subtasks
    if open_subtasks and len(active) < cap:
        subtask_agents = [a for a in open_subtasks.values()
                          if a in all_agents and a not in active]
        active.update(subtask_agents[:cap - len(active)])

    # Fill remaining slots by strategy
    remaining = [a for a in all_agents if a not in active]
    slots     = cap - len(active)

    if slots > 0 and remaining:
        if strategy == "reputation" and reputation:
            # Sample proportional to reputation (softmax-like)
            weights = [max(reputation.get(a, 0.1), 0.1) for a in remaining]
            total   = sum(weights)
            probs   = [w / total for w in weights]
            chosen  = rng.choices(remaining, weights=probs,
                                  k=min(slots, len(remaining)))
            active.update(chosen)

        elif strategy == "frontier":
            # Agents who have output but it's "old" (acted earliest)
            # Approximate: shuffle and take first `slots`
            rng.shuffle(remaining)
            active.update(remaining[:slots])

        else:  # random
            rng.shuffle(remaining)
            active.update(remaining[:slots])

    # Preserve topology order
    return [a for a in all_agents if a in active]


def active_count_for_n(n: int) -> int:
    """Expected active agents per step for population size N."""
    return min(n, get_activation_cap(n))


def log_activation(step: int, active: List[str], total: int) -> None:
    """Print a compact activation summary (only when sparse)."""
    if len(active) < total:
        print(f"    step {step}: {len(active)}/{total} agents active "
              f"({', '.join(active[:4])}{'...' if len(active) > 4 else ''})")


# ── Activation tracker — one per run ─────────────────────────

class ActivationTracker:
    """
    Tracks active_agents_per_step and unique_agents_touched for one run.
    Instantiated by the topology, passed to select_active_agents,
    and flushed into RunMetadata at run end.

    Usage in topology:
        self._activation = ActivationTracker(num_agents=self.num_agents)
        ...
        active = self._activation.record_step(step_idx, selected_agents)
        ...
        meta_kwargs = self._activation.summary()
    """

    def __init__(self, num_agents: int):
        self.num_agents          = num_agents
        self._touched: Set[str]  = set()
        self._per_step: Dict[int, int] = {}  # step_idx -> count

    def record_step(self, step_idx: int, active_agents: List[str]) -> List[str]:
        """Record which agents acted at this step. Returns active_agents unchanged."""
        self._touched.update(active_agents)
        self._per_step[step_idx] = len(active_agents)
        return active_agents

    def summary(self) -> dict:
        """Return dict suitable for RunMetadata kwargs."""
        n_touched = len(self._touched)
        steps     = list(self._per_step.values())
        mean_act  = sum(steps) / max(len(steps), 1)
        rate      = n_touched / max(self.num_agents, 1)
        return {
            "unique_agents_touched":  n_touched,
            "mean_active_per_step":   round(mean_act, 2),
            "activation_rate":        round(rate, 4),
            "active_agents_per_step": {str(k): v for k, v in self._per_step.items()},
        }

    def snapshot_kwargs(self, step_idx: int, active_agents: List[str]) -> dict:
        """Return kwargs for GraphSnapshot at this step."""
        return {
            "active_agents_this_step": active_agents,
            "num_active_this_step":    len(active_agents),
        }